// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// every other rankable pre-token protocol below the watchlist floor: the early rows the radar
// exists to find. A protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol). The snapshot's live-token protocols are kept apart: they calibrate
// the model and are shown as the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and every step is stated in the
// dashboard so a reader can check it:
//
//   multiple   = the category's market multiple, measured from the protocols that already
//                trade: the median mcap/TVL of live protocols in the same category, shrunk
//                toward the market-wide median (see calibrate). A category needs at least
//                MIN_COMPS live protocols to carry its own multiple; thinner categories use
//                the market-wide median. The multiple is capped to [MULT_CAP_LO, MULT_CAP_HI].
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   chainMult  = 1 + 0.02 x min(chains - 1, 10)
//   implied    = max(1, round(base x growthMult x maturity x chainMult))
//
// No protocol name is ever special-cased: the same function scores every row, and the same
// calibration is computed from the snapshot at every run. The program is deterministic: the
// same snapshot bytes always produce the same board bytes.

